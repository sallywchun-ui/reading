# 3. 課程渲染（單一課程共用的畫面邏輯）
# =========================================================

def render_lesson(lid: str):
    lesson = LESSONS[lid]
    _init_lesson_state(lid)
    ss = st.session_state

    meta_html = "".join(f"<div><b>{k}</b> — {v}</div>" for k, v in lesson["meta"])
    st.markdown(
        f"""
        <div class="hero">
          <div class="book-tag">세종한국어 1A</div>
          <div class="unit-row">
            <div class="unit-badge">{lesson['badge']}</div>
            <div class="unit-meta">{meta_html}</div>
          </div>
          <div class="headline">{lesson['headline']}</div>
          <span class="goal-pill">{lesson['goal']}</span>
        </div>
        """,
        unsafe_allow_html=True,
    )

    tab_vocab, tab_grammar, tab_reading, tab_quiz = st.tabs(["📖 單字", "✏️ 文法", "💬 課文", "📝 測驗"])

    # ---- 單字 ----
    with tab_vocab:
        st.markdown('<p class="vocab-hint">點擊卡片查看中文意思與例句</p>', unsafe_allow_html=True)
        for dot_label, title, words in lesson["vocab"]:
            st.markdown(
                f'<div class="section-label"><div class="dot">{dot_label}</div>'
                f'<div class="title">{title}</div></div>',
                unsafe_allow_html=True,
            )
            per_row = 3
            for row_start in range(0, len(words), per_row):
                row_words = words[row_start:row_start + per_row]
                cols = st.columns(per_row)
                for col, (kr, zh, example) in zip(cols, row_words):
                    key = f"vocab_{lid}_{dot_label}_{kr}"
                    is_revealed = key in ss[f"{lid}_revealed"]
                    with col:
                        label = f"{kr}\n\n{zh}" if is_revealed else f"{kr}\n\n點擊"
                        if st.button(label, key=key, use_container_width=True):
                            if is_revealed:
                                ss[f"{lid}_revealed"].discard(key)
                            else:
                                ss[f"{lid}_revealed"].add(key)
                            st.rerun()
                        if is_revealed and example:
                            st.markdown(
                                f'<p class="vocab-example">📖 {example}</p>',
                                unsafe_allow_html=True,
                            )

    # ---- 文法 ----
    with tab_grammar:
        for g in lesson["grammar"]:
            ex_html = ""
            for line, note in g["examples"]:
                line_hl = line.replace("<hl>", '<span class="highlight">').replace("</hl>", "</span>")
                note_html = f' <span class="gana">{note}</span>' if note else ""
                ex_html += f'<p class="ex-line">{line_hl}{note_html}</p>'
            st.markdown(
                f"""
                <div class="grammar-card">
                  <div class="pattern">{g['pattern']}</div>
                  <div class="rule">{g['rule']}</div>
                  <div class="ex-block">{ex_html}</div>
                </div>
                """,
                unsafe_allow_html=True,
            )

    # ---- 課文 ----
    with tab_reading:
        for d in lesson["dialogues"]:
            st.markdown(
                f'<div class="section-label"><div class="dot">{d["label"]}</div>'
                f'<div class="title">{d["title"]}</div></div>',
                unsafe_allow_html=True,
            )
            lines_html = ""
            for who, text, trans in d["lines"]:
                trans_html = f'<p class="trans">{trans}</p>' if trans else ""
                if who:
                    lines_html += f'<p><span class="who">{who}</span>: {text}</p>{trans_html}'
                else:
                    lines_html += f"<p>{text}</p>{trans_html}"
            st.markdown(f'<div class="dialogue">{lines_html}</div>', unsafe_allow_html=True)

    # ---- 測驗 ----
    with tab_quiz:
        scope_options = ["全部", "課文題", "延伸題"]
        scope_choice = st.radio(
            "選擇測驗範圍", scope_options, horizontal=True,
            index=scope_options.index(ss[f"{lid}_quiz_scope"]),
            label_visibility="collapsed", key=f"scope_radio_{lid}",
        )
        if scope_choice != ss[f"{lid}_quiz_scope"] or ss[f"{lid}_quiz_order"] is None:
            _start_quiz(lid, lesson, scope_choice)

        pool = _scope_pool(lesson, ss[f"{lid}_quiz_scope"])
        order = ss[f"{lid}_quiz_order"]

        if not order:
            st.info("這個分類目前沒有題目。")
        elif ss[f"{lid}_quiz_idx"] >= len(order):
            score = ss[f"{lid}_quiz_score"]
            pct = round(score / len(order) * 100)
            st.markdown(
                f"""
                <div style="text-align:center;padding:24px 8px;">
                  <div style="font-family:'Noto Serif KR',serif;font-size:48px;font-weight:700;color:var(--jade);">
                    {score}<span style="font-size:20px;color:var(--ink-soft);"> / {len(order)}</span>
                  </div>
                  <p style="color:var(--ink-soft);">答對率 {pct}%</p>
                </div>
                """,
                unsafe_allow_html=True,
            )
            if st.button("再測一次", use_container_width=True, key=f"retry_{lid}"):
                _start_quiz(lid, lesson, ss[f"{lid}_quiz_scope"])
                st.rerun()
        else:
            idx = ss[f"{lid}_quiz_idx"]
            item = pool[order[idx]]

            st.progress(idx / len(order))
            st.caption(f"第 {idx + 1} / {len(order)} 題　·　目前分數：{ss[f'{lid}_quiz_score']}")

            tag_class = "tag-extra" if item["tag"] == "延伸" else "tag-text"
            st.markdown(f'<span class="q-tag {tag_class}">{item["tag"]}</span>', unsafe_allow_html=True)
            st.markdown(f'<div class="q-text">{item["q"]}</div>', unsafe_allow_html=True)

            order_key = f"choice_order_{lid}_{ss[f'{lid}_quiz_scope']}_{idx}_{order[idx]}"
            if order_key not in ss:
                choice_idx = list(range(len(item["choices"])))
                random.shuffle(choice_idx)
                ss[order_key] = choice_idx
            choice_order = ss[order_key]

            for ci in choice_order:
                choice_text = item["choices"][ci]
                btn_key = f"opt_{order_key}_{ci}"
                if not ss[f"{lid}_answered"]:
                    if st.button(choice_text, key=btn_key, use_container_width=True):
                        ss[f"{lid}_answered"] = True
                        ss[f"{lid}_chosen"] = ci
                        if ci == item["a"]:
                            ss[f"{lid}_quiz_score"] += 1
                        st.rerun()
                else:
                    if ci == item["a"]:
                        st.success(choice_text, icon="✅")
                    elif ci == ss[f"{lid}_chosen"]:
                        st.error(choice_text, icon="❌")
                    else:
                        st.button(choice_text, key=btn_key, use_container_width=True, disabled=True)

            if ss[f"{lid}_answered"]:
                feedback = "答對了！" if ss[f"{lid}_chosen"] == item["a"] else "再想想 — 正確答案已標示為綠色。"
                st.caption(feedback)
                if st.button("下一題 →", type="primary", key=f"next_{lid}"):
                    ss[f"{lid}_quiz_idx"] += 1
                    ss[f"{lid}_answered"] = False
                    ss[f"{lid}_chosen"] = None
                    st.rerun()


